            }
        is SettingsPlaceholderGlyph ->
            HarnessIcon(
                glyph.name,
                modifier = modifier,
                tint = tint,
                size = size,
                glyphScale = placeholderScale,
            )
    }
}

/** Parses one SVG sub-path through Compose's own SVG path parser and fills it. */
private fun DrawScope.drawSettingsPath(path: SettingsIconPath, color: Color) {
    val parsed = PathParser().parsePathString(path.data).toPath()
    if (path.evenOdd) parsed.fillType = PathFillType.EvenOdd
    drawPath(parsed, color, style = Fill)
}
