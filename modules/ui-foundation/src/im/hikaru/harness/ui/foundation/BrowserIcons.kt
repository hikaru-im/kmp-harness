/**
 * Draws one [BrowserIcon] into a [size] box, filled with [tint]. Codex authors this artwork on a
 * 16x16 grid, so it is drawn at `size / 16` — the same convention [SettingsNavGlyphIcon] uses for the
 * Settings navigator artwork.
 */
@Composable
public fun BrowserIconGlyph(
    icon: BrowserIcon,
    modifier: Modifier = Modifier,
    tint: Color = HarnessTokens.Colors.Text,
    size: Dp = 16.dp,
) {
    Canvas(modifier = modifier.size(size)) {
        val box = this.size.minDimension
        val unit = box / icon.artwork.viewBox
        translate(
            left = icon.artwork.translateX * unit,
            top = icon.artwork.translateY * unit,
        ) {
            scale(scaleX = unit, scaleY = unit, pivot = Offset.Zero) {
                icon.artwork.paths.forEach { drawBrowserIconPath(it, tint) }
            }
        }
    }
}

/** Parses one SVG sub-path through Compose's own SVG path parser and fills it. */
private fun DrawScope.drawBrowserIconPath(path: BrowserIconPath, color: Color) {
    val parsed = PathParser().parsePathString(path.data).toPath()
    if (path.evenOdd) parsed.fillType = PathFillType.EvenOdd
    drawPath(parsed, color, style = Fill)
}
