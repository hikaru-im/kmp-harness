/**
 * Draws one [BrowserTabIcon] into a [size] box, filled with [tint]. Codex authors this artwork on a
 * 20-unit grid and draws it into a 16px box (`class="size-full"`), which is what this maps.
 */
@Composable
public fun BrowserTabIconGlyph(
    icon: BrowserTabIcon,
    modifier: Modifier = Modifier,
    tint: Color = HarnessTokens.Colors.Text,
    size: Dp = 16.dp,
) {
    Canvas(modifier = modifier.size(size)) {
        val unit = this.size.minDimension / icon.artwork.viewBox
        scale(scaleX = unit, scaleY = unit, pivot = Offset.Zero) {
            icon.artwork.paths.forEach { drawBrowserIconPath(it, tint) }
        }
    }
}

