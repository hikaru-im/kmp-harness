/**
 * The 新标签页 page's own glyphs: the browser toolbar's 重新加载 and 扩展程序 controls, and the 工具
 * cards' leading icons.
 *
 * They are kept apart from [HarnessIconName] on purpose, the same way the Settings artwork is: the
 * rail and title-bar glyphs were signed off in earlier batches and must not shift while this page's
 * icons are added.
 *
 * Transcribed byte-for-byte from the `<path d="…">` data the live Codex page ships — probed
 * over the remote debugging port, not eyeballed from a screenshot — together with the ink box each
 * `<svg>` reports and the translate the 扩展程序 artwork is wrapped in. The grid is Codex's 16-unit
 * icon box, so a path coordinate maps onto a [size] box by `size / 16` with no extra glyph scale.
 */
public class BrowserIconPath(public val data: String, public val evenOdd: Boolean = false)

